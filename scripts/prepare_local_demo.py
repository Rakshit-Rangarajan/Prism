"""Build a durable, hash-indexed local demo bundle without touching memory."""
import hashlib
import json
from pathlib import Path
from app.erp_samples import generate


def prepare():
    repo = Path(__file__).resolve().parents[1]
    local = repo / '.local'
    settings = json.loads((local / 'settings.json').read_text())
    company = local / 'companies' / settings['company']
    company.mkdir(parents=True, exist_ok=True)
    config = company / 'config.json'
    if not config.exists():
        config.write_text(json.dumps({'model': 'qwen3-4b', 'url': 'http://127.0.0.1:8092/v1', 'adapter': None,
                                     'business_rules': ['No automatic duplicate merging', 'Preserve invalid dates and unknown financial mappings'],
                                     'knowledge': ['Synthetic units: pieces=EA, kilograms=KG, meters=M']}, indent=2))
    manifest = {'company': settings['company'], 'model': {'path': settings['modelPath'], 'sha256': settings['modelSha256'],
                'source': 'unsloth/Qwen3-4B-Instruct-2507-GGUF', 'quantization': 'Q4_K_M'}, 'datasets': []}
    datasets = local / 'datasets'
    datasets.mkdir(exist_ok=True)
    for batch in range(1, 21):
        path = datasets / f'erp-{batch:02d}.sqlite'
        if not path.exists():
            generate(path, batch)
        # Compare with freshly generated bytes, detecting drift without overwriting.
        import tempfile
        with tempfile.TemporaryDirectory() as folder:
            expected = generate(Path(folder) / 'source.sqlite', batch).read_bytes()
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        if digest != hashlib.sha256(expected).hexdigest():
            raise ValueError(f'Dataset drift detected: {path}. Preserve it and regenerate deliberately.')
        manifest['datasets'].append({'batch': batch, 'path': str(path), 'sha256': digest})
    (local / 'artifacts.json').write_text(json.dumps(manifest, indent=2))
    print(f'Prepared 20 verified datasets for {settings["company"]}. Existing approved memory retained.')


if __name__ == '__main__':
    prepare()
