"""Offline, fail-closed migration of synthetic PRISM Migration Memory from SQLite to PostgreSQL.

This does not switch the live application database. PostgreSQL credentials are read
only from PRISM_POSTGRES_DSN; never put credentials in source control.
"""
import argparse
import os
import sqlite3
from pathlib import Path

ENTRY_COLUMNS = ("id","domain","target_object","title","resolution","evidence","version",
                 "state","reviewer","review_note","created_at","reviewed_at","supersedes_id")
EVENT_COLUMNS = ("id","entry_id","action","note","actor","created_at")
SCHEMA = """
CREATE TABLE IF NOT EXISTS memory_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 domain TEXT NOT NULL,
 target_object TEXT NOT NULL,
 title TEXT NOT NULL,
 resolution TEXT NOT NULL,
 evidence TEXT NOT NULL,
 version INTEGER NOT NULL DEFAULT 1 CHECK (version BETWEEN 1 AND 9999),
 state TEXT NOT NULL DEFAULT 'draft'
   CHECK (state IN ('draft','approved','rejected','superseded')),
 reviewer TEXT, review_note TEXT,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reviewed_at TIMESTAMP,
 supersedes_id BIGINT REFERENCES memory_entries(id)
);
CREATE TABLE IF NOT EXISTS memory_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 entry_id BIGINT NOT NULL REFERENCES memory_entries(id),
 action TEXT NOT NULL, note TEXT, actor TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS memory_scope_idx
 ON memory_entries(domain,target_object,state);
CREATE INDEX IF NOT EXISTS memory_supersedes_idx
 ON memory_entries(supersedes_id);
CREATE UNIQUE INDEX IF NOT EXISTS memory_one_draft_per_parent
 ON memory_entries(supersedes_id)
 WHERE state='draft' AND supersedes_id IS NOT NULL;
"""

def read_snapshot(path):
    """Read a source database without creating or modifying it."""
    source=Path(path).expanduser().resolve()
    if not source.is_file():
        raise FileNotFoundError(f"SQLite source does not exist: {source}")
    with sqlite3.connect(source.as_uri()+"?mode=ro",uri=True) as db:
        db.row_factory=sqlite3.Row
        names={r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if not {"memory_entries","memory_events"}.issubset(names):
            raise ValueError("Source lacks versioned Migration Memory tables")
        entries=[tuple(row[c] for c in ENTRY_COLUMNS) for row in db.execute("SELECT * FROM memory_entries ORDER BY id")]
        events=[tuple(row[c] for c in EVENT_COLUMNS) for row in db.execute("SELECT * FROM memory_events ORDER BY id")]
    event_ids={row[0] for row in events}
    if len(event_ids)!=len(events):
        raise ValueError('Duplicate source audit event identifiers')
    if any(not isinstance(row[0],int) or row[0]<=0 for row in events):
        raise ValueError('Invalid audit event identifier')
    ids={row[0] for row in entries}
    if len(ids)!=len(entries):
        raise ValueError("Duplicate source entry identifiers")
    if any(row[-1] is not None and row[-1] not in ids for row in entries):
        raise ValueError("Source contains orphaned supersession references")
    if any(row[1] not in ids for row in events):
        raise ValueError("Source contains orphaned audit events")
    # Fail closed on inconsistent governance history before touching PostgreSQL.
    by_id={row[0]:row for row in entries}
    allowed={"draft","approved","rejected","superseded"}
    drafts=set()
    for row in entries:
        identifier,domain,target_object,_,_,_,version,state,*_=row
        predecessor=row[-1]
        if not isinstance(identifier,int) or identifier<=0 or state not in allowed or not isinstance(version,int) or not 1<=version<=9999:
            raise ValueError(f"Invalid memory state/version for entry {identifier}")
        if predecessor is not None:
            parent=by_id[predecessor]
            if parent[1:3]!=(domain,target_object) or version!=parent[6]+1:
                raise ValueError(f"Invalid supersession scope/version for entry {identifier}")
            if state=="draft":
                if predecessor in drafts:
                    raise ValueError("Source contains competing draft successors")
                drafts.add(predecessor)
    # Validate the graph before assessing review state, so cycles are
    # reported accurately even when they also violate approval invariants.
    for row in entries:
        seen=set()
        cursor=row[0]
        while cursor is not None:
            if cursor in seen:
                raise ValueError("Source contains a supersession cycle")
            seen.add(cursor)
            cursor=by_id[cursor][-1]
    successors={}
    for row in entries:
        if row[-1] is not None and row[7] in ('approved','superseded'):
            successors.setdefault(row[-1],[]).append(row)
    for parent,children in successors.items():
        if len(children)>1:
            raise ValueError('Source contains competing reviewed successors')
        if by_id[parent][7] != 'superseded':
            raise ValueError('Reviewed successor has non-superseded predecessor')
    for row in entries:
        if row[7]=='superseded' and row[0] not in successors:
            raise ValueError('Superseded entry lacks a reviewed successor')
    return entries,events

def migration_plan(path):
    entries,events=read_snapshot(path)
    return {"synthetic":True,"source":"sqlite","destination":"postgresql",
            "memory_entries":len(entries),"memory_events":len(events),
            "requires_empty_destination":True}

def migrate(path,dsn):
    """All-or-nothing migration. Reject populated destinations to prevent data loss."""
    if not dsn:
        raise ValueError("PRISM_POSTGRES_DSN is required")
    try:
        import psycopg
    except ImportError as exc:
        raise RuntimeError("Install optional dependency: pip install 'psycopg[binary]>=3,<4'") from exc
    entries,events=read_snapshot(path)
    with psycopg.connect(dsn) as pg:
        with pg.transaction():
            for statement in SCHEMA.split(";"):
                if statement.strip():
                    pg.execute(statement)
            for table in ("memory_entries","memory_events"):
                count=pg.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
                if count:
                    raise ValueError(f"Destination {table} is not empty; migration aborted")
            # Insert predecessors first; defer FK checking by inserting entries
            # with NULL supersedes_id and restoring their relationships afterward.
            entry_sql="INSERT INTO memory_entries ("+",".join(ENTRY_COLUMNS)+") VALUES ("+",".join(["%s"]*len(ENTRY_COLUMNS))+")"
            for row in entries:
                pg.execute(entry_sql,row[:-1]+(None,))
            for row in entries:
                if row[-1] is not None:
                    pg.execute("UPDATE memory_entries SET supersedes_id=%s WHERE id=%s",(row[-1],row[0]))
            event_sql="INSERT INTO memory_events ("+",".join(EVENT_COLUMNS)+") VALUES ("+",".join(["%s"]*len(EVENT_COLUMNS))+")"
            for row in events:
                pg.execute(event_sql,row)
            for table in ("memory_entries","memory_events"):
                pg.execute(f"SELECT setval(pg_get_serial_sequence('{table}','id'), COALESCE((SELECT MAX(id) FROM {table}),1), (SELECT COUNT(*)>0 FROM {table}))")
            if pg.execute("SELECT COUNT(*) FROM memory_entries").fetchone()[0]!=len(entries):
                raise RuntimeError("Entry count verification failed")
            if pg.execute("SELECT COUNT(*) FROM memory_events").fetchone()[0]!=len(events):
                raise RuntimeError("Audit count verification failed")
    return {"migrated_entries":len(entries),"migrated_events":len(events),"committed":True}

def main():
    parser=argparse.ArgumentParser(description="Safely prepare or migrate PRISM synthetic Migration Memory")
    parser.add_argument("--sqlite",default=os.getenv("PRISM_DB","/tmp/prism.sqlite3"))
    parser.add_argument("--apply",action="store_true",help="Write to empty PostgreSQL destination")
    args=parser.parse_args()
    if args.apply:
        print(migrate(args.sqlite,os.getenv("PRISM_POSTGRES_DSN")))
    else:
        print(migration_plan(args.sqlite))
        print("DRY RUN ONLY. Pass --apply with PRISM_POSTGRES_DSN to migrate.")
if __name__=="__main__":
    main()
